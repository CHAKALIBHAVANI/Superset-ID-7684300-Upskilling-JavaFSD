//DataTypeDemo
class DataTypeDemo {
    public static void main(String[] args) {
        // Primitive data types
        int age = 20;
        float price = 99.5f;
        double marks = 85.75;
        char grade = 'A';
        boolean passed = true;
        System.out.println(age);
        System.out.println(price);
        System.out.println(marks);
        System.out.println(grade);
        System.out.println(passed);

    }
}