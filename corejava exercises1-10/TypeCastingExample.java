//TypeCasting
class TypeCastingExample {
    public static void main(String[] args) {
        // double to int
        double value = 45.89;
        int num = (int) value;
        // int to double
        int marks = 80;
        double newMarks = marks;
        System.out.println(num);
        System.out.println(newMarks);
    }
}